# 11. SUMMARISE FDR-SIGNIFICANT RESULTS
# ------------------------------------------------------------

summarise_significant <- function(results) {
  results %>%
    group_by(contrast) %>%
    summarise(
      n_significant = sum(
        q_BH < 0.05,
        na.rm = TRUE
      ),
      .groups = "drop"
    )
}

